#!/usr/bin/env node
//
// The JavaScript half of Web/build.sh, run after the engine and the static
// files are in dist/:
//
//   1. Compiles src/*.jsx into one dist/calc.js and app/app.jsx into
//      dist/app/app.js with the vendored Babel run in Node (no npm runtime
//      dependencies, no in-browser transform).
//   2. Copies examples/bundled.yaml and the presets it lists -- each with
//      the other files of its examples/ folder, which a preset names by
//      relative path -- into dist/presets/ (the engine's bundled examples;
//      Shared/PresetCatalog reads the list and each preset's name).
//   3. Writes dist/files.json: what the engine worker loads into its file
//      system (bundle/, presets/).
//   4. Stamps the service worker with its precache list and a hash of it.
//   5. Writes dist/MANIFEST.json: version, source commit, sha256 per file.

const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");
const { execFileSync } = require("child_process");

const WEB = __dirname;
const REPO = path.join(WEB, "..");
const DIST = path.join(WEB, "dist");

const read = (p) => fs.readFileSync(p, "utf8");
const sha256 = (buf) => crypto.createHash("sha256").update(buf).digest("hex");

function walk(dir) {
  // Dotfiles (macOS .DS_Store, editor droppings) never ship: a host that
  // ignores them would 404 on a file files.json lists.
  return fs.readdirSync(dir, { withFileTypes: true }).filter((e) => !e.name.startsWith(".")).flatMap((e) => {
    const p = path.join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}
const rel = (root, f) => path.relative(root, f).split(path.sep).join("/");

// ---- 1. Compile ---------------------------------------------------------

const sandbox = vm.createContext({ console });
vm.runInContext(read(path.join(WEB, "vendor", "babel.min.js")), sandbox, { filename: "babel.min.js" });
const Babel = sandbox.Babel;
if (!Babel) throw new Error("vendor/babel.min.js did not expose Babel");

function compile(file) {
  try {
    return Babel.transform(read(file), { presets: ["react"], sourceType: "script", compact: false, comments: true }).code;
  } catch (e) {
    throw new Error(`Babel failed on ${path.relative(WEB, file)}: ${e.message}`);
  }
}

// The one version: the Qt app's APP_VERSION.
const version = read(path.join(REPO, "Qt6", "CMakeLists.txt")).match(/set\(APP_VERSION "([0-9.]+)"\)/)[1];

// In load order; one closure, so nothing but CalcU1600 reaches the page.
const SOURCES = [
  "engine.js", "painters.js", "Faceplate.jsx", "MenuBar.jsx", "ControlBar.jsx", "Panels.jsx", "Dialogs.jsx",
  "CalcU1600.jsx",
];
const calcJs =
  "// Calc-U-1600 web client -- generated by Web/build.sh from Web/src/. Do not edit.\n" +
  "(function () {\n" +
  SOURCES.map((n) => `/* === ${n} === */\n` + compile(path.join(WEB, "src", n))).join("\n")
    .replace(/__CALC_VERSION__/g, version) +
  "\n})();\n";
fs.writeFileSync(path.join(DIST, "calc.js"), calcJs);
fs.writeFileSync(path.join(DIST, "app", "app.js"),
  "// Generated by Web/build.sh from Web/app/app.jsx. Do not edit.\n" + compile(path.join(WEB, "app", "app.jsx")));
console.log("compiled calc.js, app/app.js");

// ---- 2. Presets ---------------------------------------------------------

// Only the `file:` lines of both lists are needed here.
const bundledList = path.join(REPO, "examples", "bundled.yaml");
const presets = read(bundledList).split("\n")
  .map((line) => line.match(/^\s*(?:- )?file:\s*(\S.*?)\s*$/))
  .filter(Boolean).map((m) => m[1]);
const presetDirs = [...new Set(presets.map((f) => path.dirname(f)))];
for (const dir of presetDirs) {
  const from = path.join(REPO, "examples", dir);
  for (const f of fs.readdirSync(from, { withFileTypes: true })) {
    if (!f.isFile() || f.name.startsWith(".")) continue;
    fs.mkdirSync(path.join(DIST, "presets", dir), { recursive: true });
    fs.copyFileSync(path.join(from, f.name), path.join(DIST, "presets", dir, f.name));
  }
}
for (const f of presets)
  if (!fs.existsSync(path.join(DIST, "presets", f))) throw new Error(`bundled.yaml: ${f} is not in examples/`);
fs.copyFileSync(bundledList, path.join(DIST, "presets", "bundled.yaml"));
console.log(`presets: ${presets.length} from ${presetDirs.join(", ")}`);

// ---- 3. files.json ------------------------------------------------------

const bundleFiles = walk(path.join(DIST, "bundle")).map((f) => rel(path.join(DIST, "bundle"), f)).sort();
const presetFiles = walk(path.join(DIST, "presets")).map((f) => rel(path.join(DIST, "presets"), f))
  .sort();
fs.writeFileSync(path.join(DIST, "files.json"), JSON.stringify({ bundle: bundleFiles, presets: presetFiles }, null, 2) + "\n");

// ---- 4. Service worker --------------------------------------------------

// Every precached path must exist, or the worker's install fails in the
// browser -- caught here instead. The hash makes a new build a new cache.
const swFile = path.join(DIST, "app", "sw.js");
const generated = [...bundleFiles.map((f) => `../bundle/${f}`), ...presetFiles.map((f) => `../presets/${f}`)];
const sw = read(swFile).replace("/*__GENERATED_ASSETS__*/", generated.map((a) => JSON.stringify(a)).join(",\n  "));
const assets = sw.match(/const CORE_ASSETS = \[([\s\S]*?)\];/)[1].match(/"[^"]*"/g).map((s) => JSON.parse(s));
const swHash = crypto.createHash("sha256");
for (const a of assets) {
  const file = path.join(DIST, "app", a === "./" ? "index.html" : a);
  if (!fs.existsSync(file)) throw new Error(`app/sw.js precaches ${a}, which is not in dist/`);
  swHash.update(a).update(fs.readFileSync(file));
}
fs.writeFileSync(swFile, sw.replace("__CACHE_VERSION__", swHash.digest("hex").slice(0, 16)));
console.log(`app/sw.js: ${assets.length} precached files`);

// ---- 5. MANIFEST.json ---------------------------------------------------

const git = (...args) => execFileSync("git", ["-C", REPO, ...args], { encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD") + (git("status", "--porcelain") ? "-dirty" : "");
const files = {};
for (const f of walk(DIST).sort()) {
  const r = rel(DIST, f);
  if (r !== "MANIFEST.json") files[r] = sha256(fs.readFileSync(f));
}
fs.writeFileSync(path.join(DIST, "MANIFEST.json"),
  JSON.stringify({ name: "Calc-U-1600-web", version, commit, files }, null, 2) + "\n");
console.log(`MANIFEST.json: ${version}, ${commit}, ${Object.keys(files).length} files`);
